def build_judge_dim_system_prompt(dim: dict[str, Any]) -> str:
    """单维评分任务说明 + 五档锚点 + 纪律条款 + 输出格式（system prompt）。"""
    anchors = "\n".join(f"  {level} 分：{text}" for level, text in dim["anchors"].items())
    discipline = "\n".join(f"{i}. {rule}" for i, rule in enumerate(DISCIPLINE_RULES, 1))
    return f"""你是玄幻小说大纲的质量评审。本次只评审一个维度：{dim['key']}。其他维度的好坏与本维分数无关。

## 判定问题
{dim['question']}

## 档位锚点（1-5 整数分）
{anchors}

## 评分纪律（必须遵守）
{discipline}

## 输出格式（只输出 JSON，不要输出其他内容）
```json
{{
  "score": 0,
  "达标": ["…", "…"],
  "不足": ["…", "…"]
}}
```
- score 为 0-5 整数；证据不足以判断时打 0，此时「达标」「不足」写证据不足与所缺内容。
- 「达标」：达到所给档位的证据，逐条引原文（需求承诺点/三件套的具体段落或表述）。
- 「不足」：未达更高档的可指认缺陷或差距，逐条引原文；给 5 分且确无可指认缺陷时写 ["{NO_FLAW_PLACEHOLDER}"]。
- 两段各 1-3 条，每条一句话；不得输出本 JSON 之外的任何内容。"""


def build_judge_user_prompt(demand_md: str, deliveries: dict[str, str]) -> str:
    """评分输入：创作需求 + 三件套正文（五维共用）。

    deliveries: {logical_key 或展示名: 内容}，三件套按固定顺序拼接。
    """
    parts = [f"## 创作需求\n\n{demand_md}"]
    artifacts = "\n\n---\n\n".join(
        f"## {name}\n\n{content}" for name, content in deliveries.items()
    )
    parts.append(f"## 待评大纲（三件套）\n\n{artifacts}")
    return "\n\n".join(parts)


