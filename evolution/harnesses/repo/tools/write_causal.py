"""write_causal 工具 — 逐段写作：写一段「因果」（推剧情、闭环反应）。"""
from __future__ import annotations

from .sentence_common import build_paragraph_tool

# 说明全文单独成常量：要素页直接读它展示，页面显示的和模型读到的才是同一份文字。
WRITE_CAUSAL_TOOL_DESCRIPTION = """写一段真正推动剧情的核心因果单元，完整覆盖「触发（动作/对白/突发变故）→ 关键方与在场者反应 → 状态或局势变化」的最小因果闭环。

适用场景：
- 推进章纲中的核心事件、冲突交锋、施压与反抗、对白博弈、关键信息揭露或状态改变。
- 任何会改变人物位置、控制权、关系、认知或局势走向的实质性推进。

写法规范：
- 因果完整：段内必须交代清楚「谁做了/说了什么 → 承受者及关键在场者如何回应 → 带来了什么具体变化」，避免只写单方施为、忽略后果与现场反馈。
- 群像不失声：当重大冲突、羞辱、威慑或局势转折在多人面前发生时，必须交代关键旁观者的真实反应、立场权衡，或「为何选择沉默/不介入」的具体理由，禁止只留空壳生理动作（如全员只剩停住呼吸、沉默）。
- 动作与空间严密：写清施动者、方式与具体落点，衔接前文已确立的站位、朝向与距离，不把尚未发生的位移或接触写成既成状态；重要交锋写足细节，但不把机械微动作反复拆碎拖垮节奏。
- 对白与反应具体：原话放进引号，说话提示简洁；身体反应写具体部位与变化，内心反应写具体念头或权衡，不贴情绪标签。
- 清晰可读：单段聚焦 1 个清晰的因果回合（2–6 句），不把多个大转折硬塞进一大段；若段内包含不同角色的即时问答或动作—对白切分，可在 text 内用换行自然分段，保证一遍读懂、不混主语。

边界：
- 若本回合依赖的规则、筹码或空间位置尚未交代，先调 write_setup 或 write_info 补齐前提，严禁在因果段里硬跳结果。
- 无新因果推进的例行位移、重复过程或短暂留白，改用 write_transition 压缩或缓冲，禁止用 write_causal 刷机械动作。"""

# writing_intent 的填法随工具而异，放进参数说明让模型在填参时直接读到。
WRITE_CAUSAL_INTENT_GUIDE = (
    "按「触发动作/话语 → 目标与在场者反应 → 局势/状态变化」格式简写"
    "（如：主角抛出筹码宣告接管 → 对手失态求饶、旁观首领因顾忌后手压住质问 → 现场主导权彻底倾斜）"
)


def build(abc):
    return build_paragraph_tool(abc, "write_causal", WRITE_CAUSAL_TOOL_DESCRIPTION, WRITE_CAUSAL_INTENT_GUIDE)


__all__ = ["WRITE_CAUSAL_TOOL_DESCRIPTION", "build"]
