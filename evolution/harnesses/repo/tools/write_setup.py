"""write_setup 工具 — 逐段写作：写一段「铺垫」（立前提、埋依据）。"""
from __future__ import annotations

from .sentence_common import build_paragraph_tool

# 说明全文单独成常量：要素页直接读它展示，页面显示的和模型读到的才是同一份文字。
WRITE_SETUP_TOOL_DESCRIPTION = """写一段用于建立叙事前提的铺垫内容（人物性格与立场、势力格局与筹码、特殊/超常规则、压迫氛围或伏笔），让后续的关键转折与人物选择合情合理、有据可依。

适用场景：
- 章纲或后续剧情包含重大结果、反转、权力压制或非常规机制，动笔前需先立住「它凭什么能成立」的前置条件。
- 冲突爆发前，交代关键角色的动机、顾虑、底牌、弱点或彼此的力量悬殊。
- 需要蓄积情绪压迫感、异常征兆或心理暗流，为下一阶段的爆发蓄力。

写法规范：
- 优先「展示」而非干讲设定：通过具体细节、反常迹象、人物微表态、只言片语或克制的背景补白，把规则、筹码和氛围自然立起来。
- 每段聚焦 1 个核心前提或伏笔（2–5 句），严禁堆砌与本章无关的世界观百科。
- 写性格与情绪时落到具体言行、神态或细节征兆，禁止直接贴抽象标签（如「他心机很深」「气氛非常压抑」）。
- 只埋后文真正会用到的依据，确保与已有设定和章纲不冲突。

边界：
- 纯交代客观时间、地点、距离与物理布局（不涉及规则、立场或伏笔），改用 write_info。
- 当前提已被实际触发、演变为正面行动/对白交锋与后果落地时，改用 write_causal。
- 若前提已足够，只需在两个事件间做节奏缓冲或时间衔接，改用 write_transition。"""

# writing_intent 的填法随工具而异，放进参数说明让模型在填参时直接读到。
WRITE_SETUP_INTENT_GUIDE = (
    "按「埋下的前提/规则/立场 → 支撑后文哪个转折或选择」格式简写"
    "（如：点出某方掌握核心人质且其余人忌惮其底牌 → 支撑后文当众宣称接管时无人敢轻易出头）"
)


def build(abc):
    return build_paragraph_tool(abc, "write_setup", WRITE_SETUP_TOOL_DESCRIPTION, WRITE_SETUP_INTENT_GUIDE)


__all__ = ["WRITE_SETUP_TOOL_DESCRIPTION", "build"]
